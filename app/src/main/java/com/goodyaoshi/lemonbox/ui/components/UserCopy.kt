package com.goodyaoshi.lemonbox.ui.components

/**
 * 对「她」的称呼的唯一来源。
 *
 * 背景：这个 App 是专门做给她的，「柠檬」既是她的昵称，又是产品名「柠檬百宝箱」的一半。
