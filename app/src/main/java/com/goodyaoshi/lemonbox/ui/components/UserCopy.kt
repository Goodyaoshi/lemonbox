    /** 她的昵称（App 里对她的称呼）。要改称呼只改这一处。 */
    const val NICKNAME = "柠檬"

    /** 昵称首字，用于「我的」页头像占位。 */
    const val NICKNAME_INITIAL = "柠"
}
