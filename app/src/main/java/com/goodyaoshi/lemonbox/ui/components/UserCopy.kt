 *
 * 用法按职能分区（避免「柠檬」既指人又指产品带来的歧义）：
 * - 称呼位（对她说话、落款、头像首字）：用 [NICKNAME] / [NICKNAME_INITIAL]；
 * - 功能位（错误、提示、空状态、按钮说明）：继续用第二人称「你」，不要替换成 [NICKNAME]，
 *   否则会出现「柠檬确认一下 Wi-Fi 是否已连接」这类别扭句子；
 * - 品牌位（通知、投屏设备名、开屏、产品名）：固定用全称「柠檬百宝箱」，不在正文里简写成「柠檬」。
 */
